#!/usr/bin/env node
"use strict";

// Regenerates the commit-history table in docs/LOOP-LOG.md from real
// `git log` output on main. Run by hand before a demo/rehearsal (or any
// time the log needs refreshing), then commit normally through a PR like
// any other change — it can't run as an unattended CI commit because
// branch protection requires status checks on every push to main,
// including a bot's, and giving CI a bypass credential would undercut
// the very story this repo tells about the gate. The hand-written
// narrative sections elsewhere in the file are untouched; only the block
// between the AUTO-LOG markers is regenerated.

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const LOG_PATH = path.join(__dirname, "..", "docs", "LOOP-LOG.md");
const START = "<!-- AUTO-LOG:START -->";
const END = "<!-- AUTO-LOG:END -->";
const REPO_URL = "https://github.com/nishant7k/LoopEngineeringClaude";
const MAX_ROWS = 25;

function run(cmd) {
  return execSync(cmd, { encoding: "utf8" }).trim();
}

function buildTable() {
  const raw = run(`git log main --pretty=format:%H%x1f%s%x1f%ad --date=short -n ${MAX_ROWS}`);
  const rows = raw.split("\n").filter(Boolean).map(function (line) {
    var parts = line.split("\x1f");
    var sha = parts[0], subject = parts[1], date = parts[2];
    var short = sha.slice(0, 7);
    var prMatch = subject.match(/\(#(\d+)\)$/);
    var pr = prMatch ? "[#" + prMatch[1] + "](" + REPO_URL + "/pull/" + prMatch[1] + ")" : "—";
    var message = subject.replace(/\s*\(#\d+\)$/, "").replace(/\|/g, "\\|");
    return "| [`" + short + "`](" + REPO_URL + "/commit/" + sha + ") | " + pr + " | " + message + " | " + date + " |";
  });
  return ["| Commit | PR | Message | Date |", "|---|---|---|---|"].concat(rows).join("\n");
}

function main() {
  const content = fs.readFileSync(LOG_PATH, "utf8");
  const table = buildTable();
  const generatedAt = new Date().toISOString();
  const block = START +
    "\n<!-- Regenerated by running `node scripts/update-loop-log.js` — " +
    "do not hand-edit this block, it will be overwritten next run. Last " +
    "updated: " + generatedAt + " -->\n\n" + table + "\n\n" + END;

  const startIdx = content.indexOf(START);
  const endIdx = content.indexOf(END);
  let next;
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    next = content.slice(0, startIdx) + block + content.slice(endIdx + END.length);
  } else {
    const marker = "## Iteration 0 — Plan";
    const insertAt = content.indexOf(marker);
    const section = "## Full commit history on main (auto-generated — cannot go stale)\n\n" + block + "\n\n";
    next = insertAt === -1 ? content + "\n\n" + section : content.slice(0, insertAt) + section + content.slice(insertAt);
  }
  fs.writeFileSync(LOG_PATH, next);
}

main();
